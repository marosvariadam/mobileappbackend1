        private static Exercise New(
            string name,
            string muscleGroup,
            MovementPattern pattern,
            bool isCompound,
            ExperienceLevel minLevel,
            IEnumerable<EquipmentType> equipment,
            IEnumerable<string> secondary,
            IEnumerable<string> stressTags)
        {
            return new Exercise
            {
                Name = name,
                MuscleGroup = muscleGroup,
                SecondaryMuscleGroups = secondary.ToList(),
                MovementPattern = pattern,
                IsCompound = isCompound,
                MinLevel = minLevel,
                Equipment = equipment.ToList(),
                StressTags = stressTags.ToList(),
            };
        }
